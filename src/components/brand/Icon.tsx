interface IconProps {
  name: string;
  className?: string;
  filled?: boolean;
  weight?: 300 | 400 | 500 | 600 | 700;
  style?: CSSProperties;
}

/** Tamanho segue o font-size (text-[18px] etc.), como o Material fazia; padrão 24px via .oc-icon. */
export function Icon({ name, className = "", filled = false, weight = 400, style }: IconProps) {
  const Cmp = MAP[name];
  if (!Cmp) {
    if (import.meta.env.DEV) console.warn(`[Icon] ícone sem mapeamento para Lucide: "${name}"`);
    return <span aria-hidden className={`oc-icon ${className}`} style={style} />;
  }
  const strokeWidth = weight >= 600 ? 2.5 : weight <= 300 ? 1.5 : filled ? 2.25 : 2;
  return (
    <Cmp
      aria-hidden
      className={`oc-icon ${className}`}
      strokeWidth={strokeWidth}
      fill={filled && name === "star" ? "currentColor" : "none"}
      style={style}
    />
  );
}
